test('таблица: данные, перемещение, undo, reload и нативный PPTX', async ({ page, deckId }) => {
  await page.goto(editorUrl(deckId))
  await page.getByRole('button', { name: 'Добавить таблицу', exact: true }).click()
  await page.getByRole('textbox', { name: 'Заголовок 1', exact: true }).fill('Месяц')
  await page.getByRole('textbox', { name: 'Заголовок 2', exact: true }).fill('Продажи')
  await page.getByRole('textbox', { name: 'Строка 1, столбец 1', exact: true }).fill('Январь')
  await page.getByRole('textbox', { name: 'Строка 1, столбец 2', exact: true }).fill('42')
  await mkdir(review, { recursive: true })
  await page.screenshot({ path: resolve(review, `${test.info().project.name}-table-data.png`), fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Применить данные', exact: true }).click()
  await expect(blockOnCanvas(page)).toContainText('Январь')
  const rowHeights = await canvas(page).getByRole('table').locator('tr').evaluateAll((rows) => rows.map((row) => row.getBoundingClientRect().height))
  expect(Math.max(...rowHeights) - Math.min(...rowHeights)).toBeLessThan(2)
  await saved(page)
  await page.screenshot({ path: resolve(review, `${test.info().project.name}-table.png`), fullPage: true, animations: 'disabled' })
  await page.keyboard.press('ArrowRight')
  await page.getByRole('button', { name: 'Отменить', exact: true }).click()
  await saved(page)
  expect((await editorState(page, deckId)).slides[0].data_blocks[0]).toMatchObject({ x: 15, headers: ['Месяц', 'Продажи'], rows: [['Январь', '42'], ['Категория 2', '0'], ['Категория 3', '0']] })
  await page.getByRole('button', { name: 'Повторить', exact: true }).click()
  await saved(page)
  expect((await editorState(page, deckId)).slides[0].data_blocks[0].x).toBe(15.5)
  await page.reload()
  await expect(blockOnCanvas(page)).toContainText('Январь')
  const zip = await downloadPptx(page)
  const slides = Object.keys(zip).filter((name) => /^ppt\/slides\/slide\d+\.xml$/.test(name)).map((name) => strFromU8(zip[name]))
  expect(slides.some((xml) => xml.includes('<a:tbl>') && xml.includes('Январь') && xml.includes('42'))).toBeTruthy()
  await blockOnCanvas(page).click()
  await page.getByRole('button', { name: 'Изменить данные', exact: true }).click()
  await page.getByRole('textbox', { name: 'Строка 1, столбец 2', exact: true }).fill('999')
  await page.getByRole('button', { name: 'Отмена', exact: true }).click()
  await expect(blockOnCanvas(page)).toContainText('42')
  await expect(blockOnCanvas(page)).not.toContainText('999')
})

