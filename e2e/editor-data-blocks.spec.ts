test('API: старый клиент сохраняет блоки; некорректные данные не меняют черновик', async ({ page, deckId }) => {
  await page.goto(editorUrl(deckId))
  await page.getByRole('button', { name: 'Добавить таблицу', exact: true }).click()
  await page.getByRole('button', { name: 'Применить данные', exact: true }).click()
  await saved(page)
  const original = await editorState(page, deckId)
  const oldClient = serialize(toDeck(original), original.base_version, original.draft_revision)
  for (const slide of oldClient.slides) delete slide.data_blocks
  await mutation(page.request, 'put', `${editorApi(deckId)}/draft`, oldClient)
  const preserved = await editorState(page, deckId)
  expect(preserved.slides[0].data_blocks).toEqual(original.slides[0].data_blocks)
  const invalid = serialize(toDeck(preserved), preserved.base_version, preserved.draft_revision)
  invalid.slides[0].data_blocks![0].rows = [['Wrong number of columns']]
  const csrf = await (await page.request.get('/api/auth/csrf')).json()
  const response = await page.request.put(`${editorApi(deckId)}/draft`, { data: invalid, headers: { [csrf.data.headerName]: csrf.data.token } })
  expect(response.status()).toBe(422)
  expect((await editorState(page, deckId)).draft_revision).toBe(preserved.draft_revision)
})

test('AI: структурированные данные доходят через worker в черновик и опубликованный график', async ({ page, createdDecks }) => {
  const job = await mutation(page.request, 'post', '/api/generation/v1/presentations', {
    template_id: 'opal', topic: 'E2E data blocks 73 — столбчатая диаграмма по числу 73', mode: 'openai',
  })
  createdDecks.push(job.id)
  await expect.poll(async () => (await (await page.request.get(`/api/generation/v1/presentations/${job.id}`)).json()).status,
    { timeout: 30_000 }).toBe('draft')
  await page.goto(editorUrl(job.id))
  await expect(canvas(page).getByRole('img', { name: 'Столбчатая диаграмма', exact: true })).toBeVisible()
  expect((await editorState(page, job.id)).slides[0].data_blocks[0].rows).toEqual([['Материал', '73']])
  await page.getByRole('button', { name: 'Экспорт', exact: true }).click()
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Создать первую версию', exact: true }).click()
  expect(await (await pending).failure()).toBeNull()
  await mutation(page.request, 'post', `/api/generation/v1/presentations/${job.id}/chat`, { message: 'E2E data blocks 73: сохрани график и обнови заголовок' })
  const after = await editorState(page, job.id)
  expect(after.base_version).toBe(2)
  expect(after.slides[0].data_blocks[0].rows).toEqual([['Материал', '73']])
})
