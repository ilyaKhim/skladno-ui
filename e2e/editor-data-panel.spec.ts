import { mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import { test, expect, canvas, editorState, editorUrl, saved } from './support'

const panel = (page: import('@playwright/test').Page) => page.getByRole('region', { name: 'Данные блока', exact: true })
const preview = (page: import('@playwright/test').Page) => canvas(page).locator('[data-data-block-id]')
const review = resolve('frontend/.impeccable/review/data-panel')

test('сужение окна с открытым AI-чатом не перекрывает локальные данные', async ({ page, deckId }) => {
  await page.goto(editorUrl(deckId))
  // Explicitly open chat so it is eligible to become the mobile sheet after resizing.
  const chatToggle = page.getByRole('button', { name: 'AI-чат', exact: true })
  await chatToggle.click()
  await chatToggle.click()
  await expect(page.locator('#editor-ai-chat')).toBeVisible()
  await page.getByRole('button', { name: 'Добавить таблицу', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('#editor-ai-chat')).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Строка 1, столбец 2', exact: true }).fill('91')
  await expect(preview(page)).toContainText('91')
  await expect(canvas(page).locator('[data-slide-background]')).toHaveJSProperty('naturalWidth', 960)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await mkdir(review, { recursive: true })
  await page.screenshot({ path: resolve(review, `${test.info().project.name}-resize.png`), fullPage: true, animations: 'disabled' })
  expect((await editorState(page, deckId)).slides[0].data_blocks).toEqual([])
  await page.getByRole('button', { name: 'Применить данные', exact: true }).click()
  await expect(panel(page)).toHaveCount(0)
  await saved(page)
  expect((await editorState(page, deckId)).slides[0].data_blocks[0].rows[0][1]).toBe('91')
})

test('нижняя панель: живой предпросмотр без сохранения, отмена и явное применение', async ({ page, deckId }) => {
  await page.goto(editorUrl(deckId))
  const before = await editorState(page, deckId)
  await page.getByRole('button', { name: 'Добавить таблицу', exact: true }).click()
  await expect(panel(page)).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Заголовок 2', exact: true }).fill('Продажи')
  await page.getByRole('textbox', { name: 'Строка 1, столбец 2', exact: true }).fill('42')
  await expect(preview(page)).toContainText('Продажи')
  await expect(preview(page)).toContainText('42')
  const region = (await panel(page).boundingBox())!
  const slide = (await canvas(page).boundingBox())!
  expect(slide.y + slide.height).toBeLessThanOrEqual(region.y + 1)
  expect(slide.height).toBeGreaterThan(100)
  // Cover an autosave debounce window: local panel changes must never reach the saved deck.
  await page.waitForTimeout(1200)
  const pending = await editorState(page, deckId)
  expect(pending.draft_revision).toBe(before.draft_revision)
  expect(pending.slides[0].data_blocks).toEqual([])
  const warning = page.waitForEvent('dialog')
  const reload = page.reload({ timeout: 2000 }).catch(() => null)
  const confirmation = await warning
  expect(confirmation.type()).toBe('beforeunload')
  await confirmation.dismiss()
  await reload
  await expect(page.getByRole('textbox', { name: 'Строка 1, столбец 2', exact: true })).toHaveValue('42')
  await mkdir(review, { recursive: true })
  await page.screenshot({ path: resolve(review, `${test.info().project.name}-desktop.png`), fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Отмена', exact: true }).click()
  await expect(panel(page)).toHaveCount(0)
  await expect(preview(page)).toHaveCount(0)
  await page.getByRole('button', { name: 'Добавить таблицу', exact: true }).click()
  await page.getByRole('textbox', { name: 'Строка 1, столбец 2', exact: true }).fill('73')
  await page.keyboard.press('Control+Enter')
  await expect(panel(page)).toHaveCount(0)
  await saved(page)
  expect((await editorState(page, deckId)).slides[0].data_blocks[0].rows[0][1]).toBe('73')
  await page.getByRole('button', { name: 'Отменить', exact: true }).click()
  await expect(preview(page)).toHaveCount(0)
  await saved(page)
})

test('верхнее меню группирует графики и блоки; нижняя панель работает на узком экране', async ({ page, deckId }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(editorUrl(deckId))
  await page.getByRole('button', { name: 'Графики', exact: true }).click()
  for (const name of ['Столбчатая диаграмма', 'Линейный график', 'Кольцевая диаграмма'])
    await expect(page.getByRole('button', { name, exact: true })).toBeVisible()
  await mkdir(review, { recursive: true })
  await page.screenshot({ path: resolve(review, `${test.info().project.name}-chart-menu.png`), fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Линейный график', exact: true }).click()
  await page.getByRole('textbox', { name: 'Строка 1, столбец 2', exact: true }).fill('73')
  await expect(preview(page).locator('svg')).toHaveAttribute('aria-label', 'Линейный график')
  expect((await canvas(page).boundingBox())!.height).toBeGreaterThan(80)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: resolve(review, `${test.info().project.name}-mobile.png`), fullPage: true, animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(panel(page)).toHaveCount(0)
  expect((await editorState(page, deckId)).slides[0].data_blocks).toEqual([])
  await page.getByRole('button', { name: 'Блоки', exact: true }).click()
  await page.getByRole('button', { name: 'Сравнение', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить столбец', exact: true }).click()
  await page.getByRole('textbox', { name: 'Заголовок 4', exact: true }).fill('Ещё вариант')
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: resolve(review, `${test.info().project.name}-mobile-grid.png`), fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Закрыть данные', exact: true }).click()
  await expect(panel(page)).toHaveCount(0)
  expect((await editorState(page, deckId)).slides[0].data_blocks).toEqual([])
})
